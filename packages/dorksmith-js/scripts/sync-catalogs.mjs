// Copies the repository catalogs (../../data/*.json) into ./catalogs and regenerates
// src/catalogs.generated.ts so the package embeds them with zero runtime I/O.
// `--check` fails when the embedded copies are out of date (used in CI).
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const source = resolve(pkg, '..', '..', 'data');
const target = resolve(pkg, 'catalogs');
const generated = resolve(pkg, 'src', 'catalogs.generated.ts');
const check = process.argv.includes('--check');

if (!existsSync(source)) {
  console.log(`no repository data directory at ${source}; keeping embedded catalogs`);
  process.exit(0);
}

const files = readdirSync(source).filter(f => f.endsWith('.json')).sort();
const exportName = f => f.replace(/\.json$/, '').split(/[.\-_]/).map((p, i) => i === 0 ? p : p[0].toUpperCase() + p.slice(1)).join('');

let ts = '// GENERATED by scripts/sync-catalogs.mjs from the repository data/ directory. Do not edit.\n';
ts += "import type { OperatorCatalog, IntentCatalog, PlatformCatalog, FileTypeCatalog } from './types.js';\n\n";
const typeFor = f => f.startsWith('operators.') ? 'OperatorCatalog' : f === 'intents.json' ? 'IntentCatalog' : f === 'platforms.json' ? 'PlatformCatalog' : 'FileTypeCatalog';
const names = [];
let changed = false;
mkdirSync(target, { recursive: true });
for (const f of files) {
  const json = readFileSync(resolve(source, f), 'utf8');
  const copyPath = resolve(target, f);
  if (!existsSync(copyPath) || readFileSync(copyPath, 'utf8') !== json) { changed = true; if (!check) writeFileSync(copyPath, json); }
  const name = exportName(f);
  names.push({ name, f });
  ts += `export const ${name}: ${typeFor(f)} = ${JSON.stringify(JSON.parse(json))} as unknown as ${typeFor(f)};\n\n`;
}
ts += `/** Every catalog shipped with this package, keyed by file name. */\nexport const bundledCatalogs = {\n${names.map(n => `  ${JSON.stringify(n.f)}: ${n.name},`).join('\n')}\n} as const;\n`;
if (!existsSync(generated) || readFileSync(generated, 'utf8') !== ts) { changed = true; if (!check) writeFileSync(generated, ts); }

if (check && changed) { console.error('embedded catalogs are out of date; run `npm run sync-catalogs`'); process.exit(1); }
console.log(check ? 'embedded catalogs are up to date' : `synced ${files.length} catalog(s)`);
